import {test,expect,solve,pilot,missions} from './helpers.mjs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {cpSync,mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import {unzipSync} from 'fflate';

test('ZIP offline: campanha completa e downloads reais sem rede',async({page,context},info)=>{
 const source=resolve('.'),sandbox=info.outputPath('pacote');
 mkdirSync(sandbox,{recursive:true});
 cpSync(resolve('dist'),join(sandbox,'dist'),{recursive:true});
 execFileSync(process.execPath,[resolve('scripts/package.mjs')],{cwd:sandbox});
 const zip=readFileSync(join(sandbox,'artifacts/build.zip'));
 const checksum=readFileSync(join(sandbox,'artifacts/build.zip.sha256'),'utf8').split(/\s/)[0];
 expect(createHash('sha256').update(zip).digest('hex')).toBe(checksum);
 expect(zip.length).toBeLessThan(25*1024*1024);
 const files=unzipSync(zip),unpacked=join(sandbox,'descompactado');
 expect(Object.keys(files).sort()).toEqual(['index.html','game.js','style.css','version.json','LEIA-ME.txt','LICENSE.txt','THIRD_PARTY.txt'].sort());
 mkdirSync(unpacked,{recursive:true});
 for(const [name,bytes] of Object.entries(files))writeFileSync(join(unpacked,name),bytes);
 const version=JSON.parse(Buffer.from(files['version.json']).toString());
 expect(version.version).toBe(JSON.parse(readFileSync(join(source,'package.json'),'utf8')).version);
 expect(version.sha).toBe(process.env.GITHUB_SHA||execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim());
 expect(version.sha).toMatch(/^[a-f0-9]{40}$/);
 expect(Number.isFinite(Date.parse(version.build))).toBe(true);
 expect(Buffer.from(files['LEIA-ME.txt']).toString()).toContain('Abra index.html');
 expect(Buffer.from(files['LICENSE.txt']).toString()).toContain('Permission is hereby granted');
 expect(Buffer.from(files['THIRD_PARTY.txt']).toString()).toContain('Licen');

 const remote=[],errors=[];
 context.on('request',request=>{if(/^https?:/.test(request.url()))remote.push(request.url());});
 page.on('pageerror',error=>errors.push(error.message));
 await context.setOffline(true);
 await page.goto(pathToFileURL(join(unpacked,'index.html')).href);
 await expect(page.locator('.top-meta')).toContainText(`v${version.version}`);
 await expect(page.locator('.top-meta')).toContainText(version.sha.slice(0,7));
 await page.screenshot({path:info.outputPath('offline-menu.png'),fullPage:true});
 await page.locator('#new-game').click();
 for(let i=0;i<5;i++){await solve(page,i);await page.locator('#next-mission').click();}
 await page.locator('#test-rules').click();
 await expect(page.locator('#test-summary')).toContainText('23/23');
 await pilot(page);
 await expect(page.locator('#xp-count')).toHaveText('700 XP');
 await page.screenshot({path:info.outputPath('offline-vitoria.png'),fullPage:true});
 const pyEvent=page.waitForEvent('download');
 await page.locator('#download-python').click();
 const pyFile=info.outputPath('minhas-funcoes.py');await (await pyEvent).saveAs(pyFile);
 const python=readFileSync(pyFile,'utf8');
 for(const mission of missions.slice(0,5))expect(python).toContain(mission.reference);
 expect(python).toContain('Permission is hereby granted');
 const htmlEvent=page.waitForEvent('download');
 await page.locator('#download-game').click();
 const htmlFile=info.outputPath('meu-jogo.html');await (await htmlEvent).saveAs(htmlFile);
 expect(readFileSync(htmlFile,'utf8')).toContain('Permission is hereby granted');
 const exported=await context.newPage();
 exported.on('pageerror',error=>errors.push(error.message));
 await exported.goto(pathToFileURL(htmlFile).href);
 await exported.locator('#play').click();
 await exported.keyboard.down('ArrowRight');
 await expect.poll(async()=>Number(await exported.locator('#ship').getAttribute('data-x'))).toBeGreaterThan(280);
 await exported.keyboard.up('ArrowRight');
 await exported.screenshot({path:info.outputPath('export-jogavel-offline.png'),fullPage:true});
 expect(remote).toEqual([]);expect(errors).toEqual([]);
 const report={date:new Date().toISOString(),source:version.sha,version,method:'ZIP descompactado; file://; contexto offline antes de abrir; campanha via editor e pilotagem por teclado',zipBytes:zip.length,zipSha256:checksum,files:Object.keys(files).sort(),missions:5,finalCases:23,xp:700,remoteRequests:remote,pageErrors:errors,pythonSha256:createHash('sha256').update(python).digest('hex'),htmlSha256:createHash('sha256').update(readFileSync(htmlFile)).digest('hex')};
 const reportFile=info.outputPath('offline-integridade.json');
 writeFileSync(reportFile,JSON.stringify(report,null,2)+'\n');
 await info.attach('offline-integridade',{path:reportFile,contentType:'application/json'});
});
